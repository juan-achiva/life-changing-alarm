export function getScriptureKey(card: { text: string; reference?: string }) {
  return `${card.reference ?? ""}__${card.text}`;
}

export function pickScriptureAvoiding(usedKeys: string[] = []) {
  const blocked = new Set(usedKeys);
  const availableCards = scripturePool.filter((card) => !blocked.has(getScriptureKey(card)));
  const source = availableCards.length > 0 ? availableCards : scripturePool;
  const index = Math.floor(Math.random() * source.length);
  return source[index];
}
